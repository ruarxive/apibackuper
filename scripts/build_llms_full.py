"""Build docs/static/llms-full.txt: the pages an agent needs, as one Markdown file.

Run ``python -m scripts.build_llms_full`` after editing a listed page, or with
``--check`` to fail when the committed file is out of date.
"""

import re
import sys
from pathlib import Path

import yaml

SITE = "https://ruarxive.org/apibackuper"
OUTPUT = "docs/static/llms-full.txt"
# Pages in reading order, relative to docs/docs.
PAGES = [
    "getting-started/when-to-use.md",
    "getting-started/ai-agents.md",
    "commands/index.md",
    "commands/init.md",
    "commands/detect.md",
    "commands/validate-config.md",
    "commands/schema.md",
    "commands/run.md",
    "commands/update.md",
    "commands/export.md",
    "commands/info.md",
    "commands/verify.md",
    "configuration/index.md",
    "configuration/reference.md",
    "configuration/pagination.md",
    "configuration/http-requests.md",
    "configuration/auth.md",
    "configuration/rate-limiting-and-requests.md",
    "configuration/project-and-data.md",
    "configuration/hooks.md",
    "configuration/follow.md",
    "configuration/files.md",
    "configuration/storage.md",
    "configuration/export-filters.md",
    "getting-started/troubleshooting.md",
]
HEADER = f"""# apibackuper documentation for LLMs

> apibackuper archives paginated HTTP APIs into resumable local storage and
> exports their records to JSONL or Parquet. Configure a YAML project instead of
> writing a custom scraper.

Generated by scripts/build_llms_full.py from the documentation site; do not edit.
Agent skill: https://raw.githubusercontent.com/ruarxive/apibackuper/master/skills/apibackuper/SKILL.md
Index: {SITE}/llms.txt
"""


def page_url(relative, meta):
    """Return the published URL of a page, honouring a frontmatter slug."""
    slug = meta.get("slug") or "/" + relative[: -len(".md")]
    return SITE + slug.rstrip("/") + ("/" if meta.get("slug") else "")


def render(root):
    """Return the llms-full.txt text for the documentation under ``root``."""
    parts = [HEADER]
    for relative in PAGES:
        text = (root / "docs/docs" / relative).read_text(encoding="utf8")
        meta = {}
        match = re.match(r"^---\n(.*?)\n---\n", text, re.DOTALL)
        if match:
            meta = yaml.safe_load(match.group(1)) or {}
            text = text[match.end() :]
        text = re.sub(r"\]\((/[^)]*)\)", lambda link: f"]({SITE}{link.group(1)})", text)
        if not text.lstrip().startswith("# "):
            text = f"# {meta.get('title', relative)}\n\n{text.lstrip()}"
        parts.append(f"---\n\nSource: {page_url(relative, meta)}\n\n{text.strip()}\n")
    return "\n".join(parts)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[1]
    target = root / OUTPUT
    content = render(root)
    if "--check" in argv:
        current = target.read_text(encoding="utf8") if target.exists() else ""
        if current != content:
            print(f"{OUTPUT} is out of date; run python -m scripts.build_llms_full")
            return 1
        return 0
    target.write_text(content, encoding="utf8")
    print(f"Wrote {OUTPUT} ({len(content)} characters from {len(PAGES)} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
